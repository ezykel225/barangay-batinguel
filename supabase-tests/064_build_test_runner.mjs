// Builds the runnable migration-064 test script from the REAL migration file, so the
// harness exercises exactly the SQL that would be applied rather than a copy of it.
//
//   node supabase-tests/064_build_test_runner.mjs            > run.sql   (acceptance)
//   node supabase-tests/064_build_test_runner.mjs --negctrl  > run.sql   (negative control)
//
// It writes to stdout and never touches a database. Feed the output to psql against
// the DISPOSABLE local test database only; the harness ends in ROLLBACK.
//
// What it generates in place of the harness's preamble marker:
//   * pg_temp.m064_run(p_cfg jsonb)  -- the migration's DO body, unchanged, except that
//     its approval configuration block is replaced by `c_cfg := p_cfg`, so each test
//     supplies its own synthetic values. Negative control: a body that does nothing.
//   * pg_temp.m064_shipped_cfg()     -- the configuration exactly as shipped, so a test
//     proves the committed placeholders refuse to run.
//   * pg_temp.check(ok, msg)         -- raises (acceptance) or emits NOTICE (negative
//     control, so every failing assertion is reported instead of the first one).
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const negctrl = process.argv.includes('--negctrl')
const fail = (message) => { process.stderr.write(`064 builder: ${message}\n`); process.exit(1) }

const migration = readFileSync(join(here, '..', 'supabase-migrations', '064_legacy_data_cleanup.sql'), 'utf8').replace(/\r\n/g, '\n')
const harness = readFileSync(join(here, '064_legacy_cleanup_behavioral.sql'), 'utf8').replace(/\r\n/g, '\n')

const lines = migration.split('\n')
const once = (predicate, what) => {
  const hits = lines.flatMap((line, index) => (predicate(line) ? [index] : []))
  if (hits.length !== 1) fail(`expected exactly one ${what}, found ${hits.length}`)
  return hits[0]
}
const doStart = once((l) => l === 'do $m064$', '`do $m064$` line')
const doEnd = once((l) => l === '$m064$;', '`$m064$;` line')
const cfgStart = once((l) => l.includes('>>> 064 APPROVAL CONFIGURATION >>>'), 'configuration start marker')
const cfgEnd = once((l) => l.includes('<<< 064 APPROVAL CONFIGURATION <<<'), 'configuration end marker')
if (!(doStart < cfgStart && cfgStart < cfgEnd && cfgEnd < doEnd)) fail('markers are out of order')
if (lines.filter((l) => /^\s*(begin|commit);\s*$/i.test(l)).length !== 2) fail('expected exactly one top-level begin; and one commit;')

// Static safety checks over executable lines (comments stripped).
// Comments stripped, then string literals blanked, so text inside messages and
// privilege-name lists ('...DELETE') is never mistaken for a statement.
const code = lines.map((l) => l.replace(/--.*$/, '')).join('\n').replace(/'(?:[^']|'')*'/g, "''")
for (const [pattern, why] of [
  [/\bcascade\b/i, 'CASCADE'], [/\btruncate\b/i, 'TRUNCATE'], [/\bdrop\s+(table|function|trigger|policy|index|schema|view|column|constraint)\b/i, 'DROP'],
  [/\b(alter|create)\s+(table|function|trigger|policy|index|view)\b/i, 'DDL'], [/\b(grant|revoke)\b/i, 'GRANT/REVOKE'],
  [/\bauth\.users\b[^;]*\b(delete|update)\b|\b(delete\s+from|update)\s+auth\./i, 'Auth change'],
  [/\b(delete\s+from|update)\s+public\.(residents_registry|complaint_parties|activity_log|profiles|sms_[a-z_]+)\b/i, 'write to a protected table'],
]) if (pattern.test(code)) fail(`forbidden construct in 064: ${why}`)
const deletes = [...code.matchAll(/delete\s+from\s+public\.([a-z_]+)\s+where\s+([^;]+);/gi)].map((m) => [m[1], m[2].trim()])
const expected = ['notification_reads', 'notifications', 'reservations', 'medical_programs', 'health_events', 'medicine_stock', 'nurse_availability', 'waste_schedule']
if (JSON.stringify(deletes.map((d) => d[0])) !== JSON.stringify(expected)) fail(`delete targets/order differ: ${deletes.map((d) => d[0]).join(',')}`)
if (deletes.some(([, where]) => !/=\s*any\(v_[a-z]+\)/i.test(where))) fail('every delete must be bounded by a captured id array')
if ((code.match(/\bdelete\b/gi) || []).length !== expected.length) fail('unexpected extra DELETE')

const body = lines.slice(doStart + 1, doEnd)
const relCfgStart = cfgStart - doStart - 1
const relCfgEnd = cfgEnd - doStart - 1
const shipped = body.slice(relCfgStart + 1, relCfgEnd).join('\n')
  .replace(/^\s*c_cfg constant jsonb :=\s*/, '').replace(/;\s*$/, '')
const testBody = [...body.slice(0, relCfgStart), '  c_cfg constant jsonb := p_cfg;', ...body.slice(relCfgEnd + 1)].join('\n')

const preamble = [
  `-- generated by 064_build_test_runner.mjs (${negctrl ? 'NEGATIVE CONTROL' : 'acceptance'})`,
  negctrl
    ? `create function pg_temp.check(p_ok boolean,p_msg text) returns void language plpgsql as $c$ begin if not coalesce(p_ok,false) then raise notice 'NEGCTRL %',p_msg; end if; end $c$;`
    : `create function pg_temp.check(p_ok boolean,p_msg text) returns void language plpgsql as $c$ begin if not coalesce(p_ok,false) then raise exception '%',p_msg; end if; end $c$;`,
  `create function pg_temp.m064_shipped_cfg() returns jsonb language sql as $c$ select ${shipped} $c$;`,
  negctrl
    ? `create function pg_temp.m064_run(p_cfg jsonb) returns void language plpgsql as $m064$ begin null; end $m064$;`
    : `create function pg_temp.m064_run(p_cfg jsonb) returns void language plpgsql as $m064$\n${testBody}\n$m064$;`,
].join('\n')

const marker = '-- @@064_TEST_PREAMBLE@@'
if (harness.split(marker).length !== 2) fail('harness preamble marker must appear exactly once')
// A function replacement: a string replacement would interpret the `$$`, `$'` and
// `` $` `` sequences that SQL dollar-quoting is full of.
process.stdout.write(harness.replace(marker, () => preamble))
