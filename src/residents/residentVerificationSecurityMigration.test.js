// Static patch contracts only. These do NOT execute PostgreSQL or prove RLS.
import fs from 'fs'
import path from 'path'
const sql=fs.readFileSync(path.join(process.cwd(),'supabase-migrations/068_resident_verification_security.sql'),'utf8')
const harness=fs.readFileSync(path.join(process.cwd(),'supabase-tests/068_resident_verification_security.sql'),'utf8')
const body=sql.replace(/--[^\n]*/g,'')

test('patch is atomic, forward only, and has no data update/backfill',()=>{
 expect(body.trim()).toMatch(/^begin;/)
 expect(body.trim()).toMatch(/commit;$/)
 expect(body).not.toMatch(/\b(?:delete\s+from|truncate|drop\s+(?:table|column)|update\s+public\.)/i)
 expect(body).not.toMatch(/community_credit|person_history|person_analytics/)
})
test('both permissive update paths get explicit checks and unexpected policies stop rollout',()=>{
 expect(body).toMatch(/alter policy "Officials can verify resident accounts"[\s\S]*?using \(public.current_official_may_administer_records\(\) and role='resident'\)[\s\S]*?with check \(public.current_official_may_administer_records\(\) and role='resident'\)/)
 expect(body).toContain('using (auth.uid()=id) with check (auth.uid()=id)')
 expect(body).toContain("cmd in ('UPDATE','ALL')")
 expect(body).toContain("raise exception '068 unexpected profile UPDATE policy inventory")
})
test('protected columns fail closed and decision permission does not use broad is_official',()=>{
 expect(body).toMatch(/to_jsonb\(new\)-array\[[\s\S]*?is distinct from[\s\S]*?to_jsonb\(old\)-array/)
 expect(body).toContain("raise exception 'Protected account fields cannot be edited'")
 expect(body).not.toMatch(/public\.is_official\(/)
 expect(body).toContain("v_admin := old.role='resident' and coalesce(public.current_official_may_administer_records(),false)")
 expect(body).toContain("set search_path=''")
})
test('owner path blocks metadata tampering but preserves safe resubmission',()=>{
 expect(body).toContain('v_verification_changed and not coalesce(v_resubmit,false)')
 expect(body).toContain('new.verified_by is not distinct from old.verified_by')
 expect(body).toContain('new.verified_at is not distinct from old.verified_at')
 expect(body).toContain("old.verification_status in ('pending','rejected','verified')")
 expect(body).toContain("new.verification_status := 'pending'")
 expect(body).toContain('new.verified_by := null')
 expect(body).toContain("v_identity_changed and old.verification_status='ineligible'")
})
test('server owns stamps and trusted bypass is explicit rather than any missing JWT',()=>{
 expect(body).toContain("else v_actor end")
 expect(body).toContain("else now() end")
 expect(body).toContain("auth.role()='service_role'")
 expect(body).toContain("session_user in ('postgres','supabase_admin')")
 expect(body).toContain("coalesce(current_setting('role',true),'none') in ('none','postgres','supabase_admin')")
 expect(body).not.toMatch(/if auth\.role\(\) is null then return new/)
})
test('existing trigger binding/order is checked; notification and sync functions are not replaced',()=>{
 expect(body).toContain("tgname='trg_prevent_role_self_change'")
 expect(body).toContain("tgtype=19 and tgenabled='O'")
 expect(body).toContain("tgtype=23 and tgenabled='O'")
 expect(body).not.toMatch(/(?:drop|create)\s+trigger/i)
 expect(body).not.toMatch(/create or replace function public\.(?:sync_verified_resident_directory|notify_verification)/)
})
test('prepared database harness includes negative authorization and real role evaluation',()=>{
 expect(harness).toContain('\\ir 068_verification_test_support.sql')
 expect(harness).toContain('set local role authenticated')
 for(const label of ['ordinary cannot approve','ordinary cannot reject','ordinary cannot edit metadata','resident cannot self verify','resident cannot forge verifier','resident cannot forge decision clock','resident cannot rewrite notes','resident cannot change system identity','resident cannot alter profile email','resident cannot edit another account','Secretary approves','Punong rejects']) expect(harness).toContain(label)
 expect(fs.readFileSync(path.join(process.cwd(),'supabase-tests/068_verification_test_support.sql'),'utf8')).toContain('security invoker')
 expect(harness).toContain('\\ir 068_verification_cleanup_check.sql')
})

const support=fs.readFileSync(path.join(process.cwd(),'supabase-tests/068_verification_test_support.sql'),'utf8')
const control=fs.readFileSync(path.join(process.cwd(),'supabase-tests/068_verification_precontrol.sql'),'utf8')
const cleanup=fs.readFileSync(path.join(process.cwd(),'supabase-tests/068_verification_cleanup_check.sql'),'utf8')
